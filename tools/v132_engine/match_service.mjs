// Common v150 match service. Trusted runtime only; never publish the private record.
// Authenticated caller, trusted clock, secure random seed and curated bank are supplied
// by the hosting service. Room transactions keep state and command receipts together.
import {createHash} from 'node:crypto';
import {emptySocial,applySocial,expireSocial,socialTypes,socialView} from './social.mjs';
import {createDuel,applyDuel,publicDuel} from './duel.mjs';
import {createQuiz,applyQuiz,quizView} from './quiz.mjs';
import {createCoop,applyCoop,coopView} from './coop.mjs';
import {createTeam,applyTeam,teamView} from './team.mjs';
import {createConnectionState,connectionTransition,gameplayAllowed} from './connection.mjs';
const safe=x=>typeof x==='string'&&/^[A-Za-z0-9_-]{1,100}$/.test(x)&&!['constructor','prototype','__proto__'].includes(x);
const fail=m=>{throw Error(m)};
const clone=x=>JSON.parse(JSON.stringify(x));
const modes={duel:['classic','streak','limited','speed','strategy'],quiz:['classic','streak','limited','speed','simultaneous'],coop:['alternating','free','double','timed','perfect'],team:['classic','streak','limited','speed','strategy']};
const cefr=['A1','A2','B1','B2','C1','C2'],yds=['easy','medium','hard'];
const integer=(v,min,max)=>Number.isInteger(v)&&v>=min&&v<=max;
const hash=(...v)=>createHash('sha256').update(JSON.stringify(v)).digest('hex');
export function validateSettings(input){
 if(!input||!Object.hasOwn(modes,input.kind)||!modes[input.kind].includes(input.mode))fail('Unsupported match mode');
 const {kind,mode}=input,format=kind==='team'?input.format:kind==='quiz'?'quiz':'crossword';
 if(!['crossword','quiz'].includes(format))fail('Invalid format');
 const scale=input.scale??'cefr',allowed=scale==='cefr'?cefr:scale==='yds'?yds:null;
 if(!allowed||!Array.isArray(input.levels)||!input.levels.length||input.levels.some(x=>!allowed.includes(x)))fail('Invalid levels');
 const levels=allowed.filter(x=>input.levels.includes(x)),topic=input.topic??null,wordType=input.wordType??null;
 if(topic!==null&&!safe(topic)||wordType!==null&&!safe(wordType)||topic!==null&&wordType!==null)fail('Invalid or conflicting filters');
 const count=input.count,seconds=input.seconds??30,hints=input.hints??0,retries=input.retries??0,skipLimit=input.skipLimit??2,limit=input.limit??3,maxMistakes=input.maxMistakes??3;
 if(!integer(count,format==='quiz'?5:10,70)||!integer(seconds,0,mode==='timed'&&kind==='coop'?3600:600)||
 !integer(hints,0,20)||!integer(retries,0,3)||!integer(skipLimit,0,5)||![2,3,5].includes(limit)||!integer(maxMistakes,1,20)||
 kind==='coop'&&mode==='timed'&&seconds===0)fail('Invalid limits');
 return {kind,format,mode,scale,levels,topic,wordType,count,seconds,hints,retries,skipLimit,limit,maxMistakes};
}
export function selectBank(bank,settings,seed){
 if(!Array.isArray(bank)||typeof seed!=='string'||!seed)fail('Invalid bank');
 const accepted=bank.filter(q=>q&&safe(q.id)&&cefr.includes(q.level)&&
  settings.levels.includes(settings.scale==='cefr'?q.level:q.yds)&&
  (settings.topic===null||q.topic===settings.topic)&&(settings.wordType===null||q.wordType===settings.wordType));
 const unique=new Map();
 for(const q of accepted){const key=settings.format==='quiz'?String(q.prompt??q.clue??'').trim().toLowerCase():String(q.answer??'').trim().toUpperCase();if(key&&!unique.has(key))unique.set(key,q);}
 const ordered=[...unique.values()].sort((a,b)=>hash(seed,a.id).localeCompare(hash(seed,b.id)));
 // A crossword is generated by the trusted board builder before calling this
 // service. Keep its geometry intact rather than randomly sampling cells.
 const picked=settings.format==='crossword'?accepted:ordered.slice(0,settings.count);
 if(picked.length!==settings.count||new Set(picked.map(q=>q.id)).size!==picked.length||
  (settings.format==='crossword'&&unique.size!==picked.length))fail('Bank does not match requested count and filters');
 if(settings.levels.some(level=>!picked.some(q=>(settings.scale==='cefr'?q.level:q.yds)===level))){
  if(settings.format==='crossword')fail('Board omits a selected level');
  // Ensure every selected level is represented, then fill without duplicate questions.
  const guaranteed=settings.levels.map(level=>ordered.find(q=>(settings.scale==='cefr'?q.level:q.yds)===level));
  if(guaranteed.some(x=>!x)||guaranteed.length>settings.count)fail('Selected level has insufficient questions');
  const ids=new Set(guaranteed.map(q=>q.id));return [...guaranteed,...ordered.filter(q=>!ids.has(q.id))].slice(0,settings.count);
 }
 return picked;
}
const reducers={duel:applyDuel,quiz:applyQuiz,coop:applyCoop,team:applyTeam};
const roster=s=>Array.isArray(s.teams)?s.teams.flatMap(t=>t.members):s.players;
export function createMatch({settings,bank,players,teams,epochs,seed,now}){
 const cfg=validateSettings(settings),kind=cfg.kind,picked=selectBank(bank,cfg,seed);
 const ids=kind==='team'?teams?.flatMap(t=>t.members):players;
 if(!Array.isArray(ids)||ids.some(x=>!safe(x))||new Set(ids).size!==ids.length||
 ids.length!==(kind==='team'?4:2)||!epochs||ids.some(id=>!integer(epochs[id],1,Number.MAX_SAFE_INTEGER)))fail('Invalid roster');
 const candidates=kind==='team'?teams.map(t=>t.id):ids,first=[...candidates].sort((a,b)=>hash(seed,'first',a).localeCompare(hash(seed,'first',b)))[0];
 const common={...cfg,first,now,seed,players:ids,teams};
 const words=picked.map(q=>({answer:q.answer,clue:q.clue,cells:q.cells,level:q.level}));
 const questions=picked.map(q=>({prompt:q.prompt??q.clue,options:q.options,correct:q.correct,letterCount:q.letterCount,level:q.level}));
 let game;
 if(kind==='duel')game=createDuel({...common,words});
 if(kind==='coop')game=createCoop({...common,words});
 if(kind==='quiz')game=createQuiz({...common,questions});
 if(kind==='team')game=createTeam({...common,kind:cfg.format,items:cfg.format==='quiz'?questions.map(q=>({...q,clue:q.prompt})):words});
 const connPlayers=ids.map(id=>({id,epoch:epochs[id],team:kind==='team'?teams.find(t=>t.members.includes(id)).id:undefined}));
 const connection=createConnectionState({kind,players:connPlayers,now});
 return {schema:150,kind,settings:cfg,game,connection,revision:0,now,receipts:{},pauseAt:null,result:null,social:emptySocial(),
  presence:Object.fromEntries(ids.map(id=>[id,{session:null,until:now+12000}]))};
}
function result(s){return s.connection.phase==='finished'?s.connection.result:s.game.phase==='finished'?s.game.result:s.social?.result??null;}
function phase(s){return result(s)!==null||s.game.phase==='finished'?'finished':s.connection.phase;}
function advance(s,now){s.now=now;s.revision++;s.result=result(s);return s;}
function shiftClocks(game,delta){
 if(typeof game.deadline==='number')game.deadline+=delta;
 if(game.current)for(const c of Object.values(game.current))if(typeof c.deadline==='number')c.deadline+=delta;
}
function engineCommand(s,cmd){
 const c={...cmd,revision:s.game.revision};
 if(s.kind==='quiz')c.index=cmd.index;
 return c;
}
export function matchCommand(state,uid,cmd,now){
 if(!roster(state.game).includes(uid)||!cmd||!safe(cmd.id)||cmd.actor!==undefined&&cmd.actor!==uid||
 !Number.isSafeInteger(now)||now<state.now)fail('Unauthorized or invalid command');
 const receipt=uid+':'+cmd.id;
 if(Object.hasOwn(state.receipts,receipt))return state;
 if(phase(state)!=='playing'||!gameplayAllowed(state.connection,uid))fail('Match not active');
 if(socialTypes.has(cmd.type)){
  const s=clone(state),eligible=s.connection.players.filter(p=>!p.removed&&p.connected).map(p=>p.id);
  s.social=applySocial(s.social??emptySocial(),uid,cmd,now,eligible);
  s.receipts[receipt]=s.revision+1;s.now=now;s.result=result(s);return s;
 }
 const concurrentQuiz=state.kind==='quiz'&&['speed','simultaneous'].includes(state.game.mode)&&
  cmd.index===state.game.index&&Number.isInteger(cmd.revision)&&cmd.revision>=0&&cmd.revision<state.revision;
 if(cmd.revision!==state.revision&&!concurrentQuiz)fail('Stale match revision');
 if(cmd.type==='leave'||cmd.type==='tick')fail('Transport operations require trusted gateway');
 const s=clone(state);
 // Internal command ID is actor-scoped and bounded; client IDs cannot collide.
 const c=engineCommand(s,{...cmd,actor:uid,id:hash(receipt)});
 s.game=reducers[s.kind](s.game,c,now);
 if(s.game===state.game)return state;
 s.receipts[receipt]=s.revision+1;
 return advance(s,now);
}
export function matchTransport(state,event,now){
 if(!Number.isSafeInteger(now)||now<state.now)fail('Invalid server time');
 if(phase(state)==='finished')return state;
 const connection=connectionTransition(state.connection,event,now);
 if(connection===state.connection)return state;
 const s=clone(state);s.connection=connection;
 if(state.connection.phase==='playing'&&connection.phase==='paused')s.pauseAt=now;
 if(state.connection.phase==='paused'&&connection.phase==='playing'){
  shiftClocks(s.game,Math.max(0,now-(s.pauseAt??now)));s.pauseAt=null;
 }
 if(s.kind==='team'){
  // Departed team members must be removed in the gameplay reducer as well.
  for(const p of connection.players)if(p.removed&&!s.game.removed.includes(p.id))s.game.removed.push(p.id);
 }
 return advance(s,now);
}
export function matchTick(state,now){
 let after=matchTransport(state,{type:'tick'},now);
 const expired=expireSocial(after.social??emptySocial(),now);
 if(after.social&&expired!==after.social){after={...after,social:expired,now};}
 if(phase(after)!=='playing')return after;
 const s=clone(after),cmd={id:hash('tick',s.revision,now),type:'tick',revision:s.game.revision,index:s.game.index};
 const next=reducers[s.kind](s.game,cmd,now);
 if(next===s.game)return after;
 s.game=next;return advance(s,now);
}
export function matchView(s,uid,at=s.now){
 if(!roster(s.game).includes(uid))fail('Not a participant');
 const game=s.kind==='duel'?publicDuel(s.game,uid):s.kind==='coop'?coopView(s.game):s.kind==='quiz'?quizView(s.game,uid):teamView(s.game,uid);
 // Never leak transport epochs, private bank, seed or other players' hint claims.
 return clone({schema:150,kind:s.kind,settings:s.settings,revision:s.revision,phase:phase(s),result:s.result,
  connection:{phase:s.connection.phase,pausedAt:s.pauseAt,players:s.connection.players.map(({id,connected,drops,until,removed,reason})=>({id,connected,drops,until,removed,reason}))},
  serverNow:at,social:socialView(s.social??emptySocial(),at),game});
}
// The ref must point to a private Admin-only match record. No public projection
// is ever written to the legacy room; return the caller's view after committing.
export async function transactMatch(ref,uid,cmd,now){
 const tx=await ref.transaction(state=>{
  if(!state)fail('Match not found');
  const next=matchCommand(state,uid,cmd,now);return next===state?undefined:next;
 },undefined,false);
 return {committed:tx.committed,view:matchView(tx.snapshot.val(),uid)};
}
