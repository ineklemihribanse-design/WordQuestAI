import fs from 'node:fs';
import assert from 'node:assert/strict';
import {initializeTestEnvironment,assertFails,assertSucceeds} from '@firebase/rules-unit-testing';
const env=await initializeTestEnvironment({projectId:'demo-wordquest',database:{host:'127.0.0.1',port:9000,rules:fs.readFileSync('firebase/database.rules.v132.json','utf8')}});
try {
 const day=Math.floor((Date.now()+10800000)/86400000),uid='quota-user',other='other-user';
 const db=env.authenticatedContext(uid,{firebase:{sign_in_provider:'google.com'}}).database();
 const second=env.authenticatedContext(uid,{firebase:{sign_in_provider:'google.com'}}).database();
 const guest=env.authenticatedContext(other,{firebase:{sign_in_provider:'password'}}).database();
 const anon=env.authenticatedContext('anon',{firebase:{sign_in_provider:'anonymous'}}).database();
 const quota='roomQuotaV2/'+uid+'/'+day;
 const old='roomQuota/'+uid+'/'+day;
 await env.withSecurityRulesDisabled(async c=>{await c.database().ref(old+'/0').set('OLD000001');});
 assert.equal((await db.ref(quota).get()).exists(),false);
 const create=(i,code,patch={})=>({[quota+'/'+i]:code,['rooms/'+code]:{hostUid:uid,mode:'words',phase:'lobby',createdAt:Date.now(),quotaDay:day,quotaSlot:String(i),...patch}});
 await assertFails(db.ref(quota+'/0').set('ROOM00000'));
 await assertFails(db.ref().update(create(0,'ROOM00000',{mode:'invalid'})));
 assert.equal((await db.ref(quota+'/0').get()).exists(),false);
 await assertSucceeds(db.ref().update(create(0,'ROOM00000')));
 await env.withSecurityRulesDisabled(async c=>{await c.database().ref('users/'+uid+'/nickname').set('QuotaUser');});
 const custom='custom_'+'a'.repeat(32);
 const premium=(i,code,patch={})=>({[quota+'/'+i]:code,['premiumRooms/'+code]:{hostUid:uid,hostName:'QuotaUser',phase:'lobby',mode:'duel',level:'A1',topic:'all',size:30,seconds:30,boardId:'test-board',quizSeed:123,turn:{uid,until:0},createdAt:Date.now(),quotaDay:day,quotaSlot:String(i),hostAvatar:custom,configRevision:1,rulesVersion:2,package6:{settings:{levels:'A1,A2',hints:3,retries:1}},...patch}});
 await assertFails(db.ref().update(premium(1,'PRM000001',{size:31})));
 assert.equal((await db.ref(quota+'/1').get()).exists(),false);
 await assertFails(db.ref().update(premium(1,'PRM000001',{hostAvatar:'custom_invalid'})));
 assert.equal((await db.ref(quota+'/1').get()).exists(),false);
 await assertSucceeds(db.ref().update(premium(1,'PRM000001')));
 const preview=custom+':'+'A'.repeat(180);
 await assertSucceeds(db.ref('premiumRooms/PRM000001/hostMascotPreview').set(preview));
 await assertFails(guest.ref('premiumRooms/PRM000001/hostMascotPreview').set(preview));
 await assertFails(db.ref('premiumRooms/PRM000001/hostMascotPreview').set('custom_'+'b'.repeat(32)+':'+'A'.repeat(180)));
 await assertSucceeds(db.ref('premiumRooms/PRM000001/hostMascotPreview').remove());
 const hd=custom+':'+'A'.repeat(120000);
 const hdPath='premiumRooms/PRM000001/hostMascotHd';
 await assertSucceeds(db.ref(hdPath).set(hd));
 await assertFails(guest.ref(hdPath).get());
 await assertFails(guest.ref(hdPath).set(hd));
 await assertFails(db.ref(hdPath).set('custom_'+'b'.repeat(32)+':'+'A'.repeat(120000)));
 await assertFails(db.ref(hdPath).set(custom+':'+'A'.repeat(181000)));
 await assertFails(db.ref(hdPath).set(custom+':'+'!'.repeat(200)));
 await assertSucceeds(db.ref('premiumRooms/PRM000001/hostMascotPreview').set(preview));
 await assertSucceeds(db.ref(hdPath).remove());
 await assertSucceeds(db.ref('premiumRooms/PRM000001/hostMascotPreview').remove());
 await assertFails(db.ref().update(premium(1,'PRM000002')));
 await assertFails(second.ref().update(create(0,'ROOM99999')));
 await assertFails(guest.ref(quota).get());
 await assertFails(anon.ref().update(create(1,'ROOM00001')));
 // A hybrid round is an immutable snapshot tied to the configuration revision.
 const webId='web:'+'a'.repeat(64), path='premiumRooms/WEB000001';
 const payload=JSON.stringify({ok:true,data:{words:[['APPLE','elma','A1',0,0,'A']]}});
 await assertFails(db.ref().update(premium(2,'WEB000001',{boardId:webId})));
 await assertFails(db.ref().update(premium(2,'WEB000001',{boardId:webId,roundData:'x'.repeat(49153)})));
 await assertSucceeds(db.ref().update(premium(2,'WEB000001',{boardId:webId,roundData:payload})));
 await env.withSecurityRulesDisabled(async c=>{await c.database().ref(path).update({guestUid:other,guestName:'Other'});});
 await assertFails(db.ref(path+'/ready/'+uid).set(1));
 await assertFails(guest.ref(path+'/ready/'+other).set(1));
 await assertFails(guest.ref(path+'/roundAck/'+uid).set(1));
 await assertFails(guest.ref(path+'/roundData').set('tamper'));
 await assertFails(db.ref(path+'/roundData').set('tamper'));
 await assertSucceeds(db.ref(path+'/roundAck/'+uid).set(1));
 await assertSucceeds(db.ref(path+'/ready/'+uid).set(1));
 await assertFails(db.ref(path+'/phase').set('playing'));
 await assertSucceeds(guest.ref(path+'/roundAck/'+other).set(1));
 await assertSucceeds(guest.ref(path+'/ready/'+other).set(1));
 await assertSucceeds(db.ref(path).update({configRevision:2,boardId:'web:'+'b'.repeat(64),roundData:payload+' ',"package6/settings":{levels:'A1,A2,B1',hints:5,retries:1}}));
 await assertFails(db.ref(path+'/phase').set('playing'));
 await assertFails(guest.ref(path+'/ready/'+other).set(2));
 await assertFails(db.ref(path+'/roundAck/'+uid).set(1));
 await assertSucceeds(db.ref(path+'/roundAck/'+uid).set(2));
 await assertSucceeds(guest.ref(path+'/roundAck/'+other).set(2));
 await assertSucceeds(db.ref(path+'/ready/'+uid).set(2));
 await assertSucceeds(guest.ref(path+'/ready/'+other).set(2));
 await assertSucceeds(db.ref(path+'/phase').set('playing'));
 await assertFails(db.ref(path).update({configRevision:3,roundData:'tamper'}));
 await assertFails(guest.ref(path+'/roundAck/'+other).set(3));
 console.log('PASS hybrid snapshot authorization, revision gate, stale/legacy clients blocked, immutable active round');
 // New reactions preserve participant-only writes, timestamp and cooldown.
 const emoji=path+'/package6/emoji/';
 const react=(symbol)=>({symbol,sentAt:Date.now()});
 await assertSucceeds(db.ref(emoji+uid).set(react('❤️')));
 assert.equal((await guest.ref(emoji+uid).get()).val().symbol,'❤️');
 await assertFails(db.ref(emoji+uid).set(react('😮')));
 await assertFails(guest.ref(emoji+uid).set(react('😮')));
 await assertFails(anon.ref(emoji+'anon').set(react('❤️')));
 await assertFails(guest.ref(emoji+other).set(react('not-allowed')));
 await assertFails(guest.ref(emoji+other).set({symbol:'😮',sentAt:Date.now()-180000}));
 await assertSucceeds(guest.ref(emoji+other).set(react('😮')));
 assert.equal((await db.ref(emoji+other).get()).val().symbol,'😮');
 await new Promise(resolve=>setTimeout(resolve,700));
 await assertSucceeds(db.ref(emoji+uid).set(react('👏')));
 console.log('PASS v148 reaction authorization, bidirectional delivery, cooldown and legacy reactions');
 for(let i=3;i<20;i++) await assertSucceeds(db.ref().update(create(i,'ROOM'+String(i).padStart(5,'0'))));
 await assertFails(db.ref().update(create(20,'ROOM00020')));
 await assertFails(db.ref(old+'/1').set('OLD000002'));
 assert.equal((await db.ref(quota).get()).numChildren(),20);
 console.log('PASS atomic 20/day, failed create not charged, old ledger retained, account isolation');
} finally {await env.cleanup();}
