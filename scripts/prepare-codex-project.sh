#!/usr/bin/env bash
set -euo pipefail
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
src_zip="$repo_root/wq-noaudio.zip"
project_root="$repo_root/app-project"
if [[ ! -f "$src_zip" ]]; then
  echo "WordQuest source archive was not found: $src_zip" >&2
  exit 1
fi
mkdir -p "$project_root"
# -n never overwrites edits already made by a coding agent.
unzip -n -q "$src_zip" -d "$project_root"
test -f "$project_root/settings.gradle.kts"
test -f "$project_root/gradlew"
chmod +x "$project_root/gradlew"
printf 'Android Studio project ready at: %s\n' "$project_root"
printf '%s\n' 'Open this folder in Android Studio, or ask Codex to make edits and run the Gradle tests there.'
printf '%s\n' 'Note: the initial audio assets are omitted; they are regenerated by the existing build workflow.'

# Stage the separate Lena avatar asset without changing Alex or the existing UI.
python3 "$repo_root/scripts/stage-lena-assets.py"
